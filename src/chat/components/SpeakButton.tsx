import { AlertCircle, Loader2, Pause, Play, Square, Volume2 } from "lucide-react";
import { useReadAloudContext } from "../hooks/useReadAloud";

// The read-aloud control of one reply (RFC FX). Nothing renders where
// read-aloud is not offered. One reply reads at a time: starting another stops
// this one. A failure is told on the reply it happened to.
export default function SpeakButton({ speechKey, text }: { speechKey: string; text: string }) {
  const speech = useReadAloudContext();
  if (!speech) return null;
  const { state } = speech;
  const failure = state.error?.key === speechKey ? state.error.message : null;

  if (state.unavailable) {
    return failure ? <span className="speak-error" role="status">{failure}</span> : null;
  }

  if (state.key !== speechKey || state.status === "idle") {
    return (
      <>
        <button
          type="button"
          className="copy-btn speak-btn"
          onClick={() => speech.play(speechKey, text)}
          title={failure ? "Read aloud again" : "Read aloud"}
          aria-label="Read aloud"
        >
          {failure ? <AlertCircle size={14} className="speak-failed" /> : <Volume2 size={14} />}
        </button>
        {failure && (
          <span className="speak-error" role="status">
            {failure}
          </span>
        )}
      </>
    );
  }

  const loading = state.status === "loading";
  const paused = state.status === "paused";
  return (
    <>
      {loading ? (
        <button type="button" className="copy-btn speak-btn" disabled title="Preparing audio…" aria-label="Preparing audio">
          <Loader2 size={14} className="spin" />
        </button>
      ) : (
        <button
          type="button"
          className="copy-btn speak-btn"
          onClick={paused ? speech.resume : speech.pause}
          title={paused ? "Resume" : "Pause"}
          aria-label={paused ? "Resume" : "Pause"}
        >
          {paused ? <Play size={14} /> : <Pause size={14} />}
        </button>
      )}
      <button type="button" className="copy-btn speak-btn" onClick={speech.stop} title="Stop reading" aria-label="Stop reading">
        <Square size={14} />
      </button>
      <span className="speak-label" title="The voice is generated by the speech engine">
        AI voice
      </span>
    </>
  );
}
